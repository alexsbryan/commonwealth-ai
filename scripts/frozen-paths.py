#!/usr/bin/env python3
"""The corpus, evidence and deep-research slice moved to corpus-engine-core
(step one of the lift closed 2026-10-23). Its files here are frozen: new work
on them goes there.

  frozen-paths.py check <commit-msg-file>
      Run by scripts/commit-msg.sh. Refuses a commit that changes a frozen
      path unless its message carries a `Frozen-path:` trailer saying why: a
      backport of a corpus-engine-core fix that a consumer here needs, or a
      change elsewhere these files must follow so commonwealth-ai builds.
  frozen-paths.py refresh <corpus-engine-core dir>
      Regenerates quality/frozen-paths.txt from that repository's
      scripts/ports.py PAIRS (the files it lifted from here), keeping the
      pairs under MOVED. The list is generated, never edited by hand.

MOVED names the work that moved, not everything the port copied: the port
also carries shared infrastructure it needed to compile (sovereign-contracts,
kernel-types, host-kit, oicp-client, the grounding gate the chat pipeline
uses), and those stay open here. A file of a MOVED crate that the port did
not lift (a dropped chunker, a pass pack) stays open too.
"""
import importlib.util
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = ROOT / "quality/frozen-paths.txt"
TRAILER = re.compile(r"^Frozen-path:[ \t]*\S", re.M)
SHOWN = 12

MOVED = (
    "ingest/crates/corpus-engine/",
    "ingest/crates/sovereign-recipes/",
    "ingest/crates/sovereign-enrichment-build/",
    "ingest/crates/sovereign-enrichment-catalog/",
    "ingest/crates/understanding-atlas/",
    "shared/crates/corpus-index/",
    "shared/crates/corpus-engine-atlas-reader/",
    "shared/crates/corpus-engine-sections/",
    "shared/crates/corpus-engine-yield/",
    "shared/crates/understanding-vocab/",
    "shared/crates/quote-align/",
    "shared/crates/oicp-types/src/evidence",
    "shared/crates/oicp-types/src/verify",
    "svrn/crates/sovereign-core/src/deep_research/",
    "svrn/crates/sovereign-core/src/quote_verification",
    "svrn/crates/sovereign-core/tests/golden/drb1-",
    "svrn/crates/sovereign-daemon/src/research_http.rs",
    "svrn/crates/sovereign-daemon/src/search_stage.rs",
    "svrn/crates/sovereign-daemon/src/oicp_evidence.rs",
    "svrn/crates/sovereign-daemon/src/records_by_identifier",
    "svrn/crates/sovereign-daemon/src/sentence_index",
    "svrn/crates/sovereign-daemon/src/routes_knowledge",
    "svrn/crates/sovereign-daemon/src/routes_oicp",
    "svrn/crates/sovereign-daemon/data/record_resolvers.toml",
    "svrn/crates/sovereign-daemon/data/sentence_search.toml",
    "svrn/crates/sovereign-daemon/tests/main/oicp_",
    "svrn/crates/sovereign-daemon/tests/main/research_surface_e2e.rs",
    "svrn/crates/sovereign-daemon/tests/fixtures/records/",
)

WHY = """\
The corpus, evidence and deep-research slice moved to corpus-engine-core
(github.com/alexsbryan/corpus-engine-core); work on these files goes there.
If this change must land here anyway (a backport of a corpus-engine-core fix
that a consumer here needs, or a change elsewhere these files must follow so
commonwealth-ai builds), add a trailer saying why, e.g.
    Frozen-path: backport of corpus-engine-core <sha>
AGENTS.md, "Frozen: the slice that moved to corpus-engine-core", has the rest."""


def git(*args):
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True,
                          text=True, check=True).stdout


def frozen():
    return {l for l in LIST.read_text().splitlines() if l and not l.startswith("#")}


def check(msg_file):
    staged = git("diff", "--cached", "--name-only", "-z").split("\0")
    hits = sorted(set(staged) & frozen())
    if not hits or TRAILER.search(pathlib.Path(msg_file).read_text()):
        return 0
    print(f"commit-msg: this commit changes {len(hits)} frozen file(s):", file=sys.stderr)
    for p in hits[:SHOWN]:
        print(f"  {p}", file=sys.stderr)
    if len(hits) > SHOWN:
        print(f"  ... and {len(hits) - SHOWN} more", file=sys.stderr)
    print(WHY, file=sys.stderr)
    return 1


def refresh(cec):
    cec = pathlib.Path(cec).resolve()
    spec = importlib.util.spec_from_file_location("ports", cec / "scripts/ports.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    tracked = set(git("ls-files").splitlines())
    paths = sorted({up for up, _ in mod.PAIRS if up.startswith(MOVED) and up in tracked})
    sha = subprocess.run(["git", "-C", str(cec), "rev-parse", "--short", "HEAD"],
                         capture_output=True, text=True, check=True).stdout.strip()
    LIST.write_text(
        "# Frozen: files of the slice that moved to corpus-engine-core.\n"
        f"# Generated by `scripts/frozen-paths.py refresh <corpus-engine-core>` from its\n"
        f"# scripts/ports.py at {sha}; never edit by hand. Read by scripts/commit-msg.sh.\n"
        + "".join(p + "\n" for p in paths))
    print(f"frozen-paths: {len(paths)} paths from corpus-engine-core {sha} -> {LIST.relative_to(ROOT)}")
    return 0


def main(argv):
    if len(argv) == 2 and argv[0] == "check":
        return check(argv[1])
    if len(argv) == 2 and argv[0] == "refresh":
        return refresh(argv[1])
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
